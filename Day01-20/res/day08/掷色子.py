# 将一颗色子掷6000次，统计每种点数出现的次数
# 模拟掷骰子6000次并统计各点数出现次数的程序
import random

# 创建一个包含6个元素的列表，初始值均为0，用于记录每个点数出现的次数
# 索引0对应点数1，索引1对应点数2，以此类推
counters = [0] * 6

# 循环6000次模拟掷骰子过程
for _ in range(6000):
    # 生成1-6之间的随机整数，表示骰子的点数
    face = random.randrange(1, 7)
    # 将对应点数的计数器加1（因列表索引从0开始，需将点数减1）
    counters[face - 1] += 1

# 遍历1-6的点数，打印每个点数出现的次数
for face in range(1, 7):
    # 使用f-string格式化输出，显示点数及其对应的出现次数
    print(f'{face}出现了{counters[face - 1]}次')
