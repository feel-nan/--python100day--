# > **要求**：输入华氏温度将其转换为摄氏温度，华氏温度到摄氏温度的转换公式为： $\small{C = (F - 32) / 1.8}$ 。
# f = float(input('请输入华氏温度：'))
# c = (f - 32) / 1.8
# print('华氏温度转换为摄氏温度后的结果为：%.2f' % c)

f = float(input('请输入华氏温度: '))
# 使用 input 函数提示用户输入华氏温度，返回的是字符串类型
# 再使用 float 函数将输入的字符串转换为浮点数类型，并赋值给变量 f

c = (f - 32) / 1.8
# 根据转换公式 (F - 32) / 1.8 计算对应的摄氏温度
# 将计算结果赋值给变量 c

print('%.1f华氏度 = %.1f摄氏度' % (f, c))
# 使用 % 格式化字符串的方式输出结果
# %.1f 表示将浮点数保留一位小数进行输出
# 分别将变量 f 和 c 的值填充到对应的占位符中
