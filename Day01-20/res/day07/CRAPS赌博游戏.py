# CRAPS又称花旗骰，是美国拉斯维加斯非常受欢迎的一种的桌上赌博游戏。
# 该游戏使用两粒骰子，玩家通过摇两粒骰子获得点数进行游戏。
# 简化后的规则是：
# 玩家第一次摇骰子如果摇出了 7 点或 11 点，玩家胜；
# 玩家第一次如果摇出 2 点、3 点或 12 点，庄家胜；
# 玩家如果摇出其他点数则游戏继续，玩家重新摇骰子，如果玩家摇出了 7 点，庄家胜；
# 如果玩家摇出了第一次摇的点数，玩家胜；
# 其他点数玩家继续摇骰子，直到分出胜负。
# 为了增加代码的趣味性，我们设定游戏开始时玩家有 1000 元的赌注，
# 每局游戏开始之前，玩家先下注，如果玩家获胜就可以获得对应下注金额的奖励，
# 如果庄家获胜，玩家就会输掉自己下注的金额。游戏结束的条件是玩家破产（输光所有的赌注）。

import random

# 初始化玩家的总资金为 10000 元
money = 10000
# 外层循环，只要玩家的资金大于 0，游戏就继续进行
while money > 0:
    # 打印当前玩家的总资金
    print(f'你的总资为：{money}元')
    # 内层循环，用于获取玩家的有效下注金额
    while True:
        # 提示玩家输入下注金额，并将输入转换为整数
        debt = int(input('请下注：'))
        # 检查下注金额是否在有效范围内（大于 0 且不超过当前总资金）
        if 0 < debt <= money:
            # 若下注金额有效，跳出内层循环
            break

    # 模拟第一次摇骰子，每个骰子点数范围是 1 到 6，两个骰子点数相加得到第一次摇的点数
    # 原代码 random.randint(1,7) 有误，骰子最大点数为 6，应改为 random.randint(1,6)
    first_point = random.randint(1,6) + random.randint(1,6)
    # 打印第一次摇到的点数
    print(f'第一次摇到的点数为：{first_point}')

    # 判断第一次摇骰子的结果
    if first_point == 7 or first_point == 11:
        # 若第一次摇到 7 点或 11 点，玩家获胜
        print('你赢了')
        # 玩家资金增加下注金额
        money += debt
    elif first_point == 2 or first_point == 3 or first_point == 12:
        # 若第一次摇到 2 点、3 点或 12 点，庄家获胜
        print('庄家赢了')
        # 玩家资金减少下注金额
        money -= debt
    else:
        # 若第一次摇到其他点数，游戏继续，进入重新摇骰子的循环
        while True:
            # 模拟重新摇骰子，同样两个骰子点数相加
            # 原代码 random.randrange(1,7) 有误，应改为 random.randrange(1,7)
            re_point = random.randrange(1,7) + random.randrange(1,7)
            # 打印重新摇到的点数
            print(f'重新摇到的点数为：{re_point}')
            if re_point == 7:
                # 若重新摇到 7 点，庄家获胜
                print('庄家赢了')
                # 玩家资金减少下注金额
                money -= debt
                # 跳出重新摇骰子的循环
                break
            elif re_point == first_point:
                # 若重新摇到的点数和第一次相同，玩家获胜
                print('你赢了')
                # 玩家资金增加下注金额
                money += debt
                # 跳出重新摇骰子的循环
                break

# 当玩家资金为 0 时，游戏结束，打印破产信息
print('你破产了，游戏结束')
